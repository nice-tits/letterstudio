export function getPost(slug) {
  if (typeof slug !== 'string') return null;
  return POSTS[slug.trim().toLowerCase()] ?? null;
}

export function allPosts() {
  return Object.values(POSTS).sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)));
}
